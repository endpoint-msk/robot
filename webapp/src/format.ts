// Форматирование сумм. Один хелпер на весь миниапп: до этого плашка взноса на
// «Ближайших днях» подставляла число сырым, а экран взносов — с разделителем
// разрядов, и одна и та же сумма выглядела по-разному в одном тапе друг от друга.

/** `2 222 ₽`: в столбце сумм неразделённые тысячи не читаются. Разряды делит узкий
    неразрывный пробел (U+202F): обычный на этом кегле разрывает число пополам, а
    тонкий U+2009 разрешает перенос строки посреди суммы. Перед валютой пробел тоже
    неразрывный, иначе «₽» уезжает на следующую строку одна. */
export const money = (n: number, currency: string): string =>
  `${String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, '\u202f')}\u00a0${currency}`
